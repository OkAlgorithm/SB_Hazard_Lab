export interface ArtView { scale: number; x: number; y: number }
export function artView(scale: number, centerX: number, centerY: number): ArtView {
  const s = Math.max(1, Math.min(4, scale));
  const clamp = (v: number) => Math.max(1 - s, Math.min(0, v));
  return { scale: s, x: clamp(0.5 - centerX * s), y: clamp(0.5 - centerY * s) };
}

export function panArt(view: ArtView, dx: number, dy: number): ArtView {
  const clamp = (v: number) => Math.max(1 - view.scale, Math.min(0, v));
  return { ...view, x: clamp(view.x + dx), y: clamp(view.y + dy) };
}
